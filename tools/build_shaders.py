#!/usr/bin/env python3
"""
Compiles shaders/*.hlsl to D3D9 SM3 bytecode and writes include/ts2/postfx_shaders_gen.hpp.

No DirectX SDK needed: tools/shadercomp/hlslc.cpp is a tiny Windows exe that calls D3DCompile from Wine's
d3dcompiler_47.dll. It is built with the same clang/lld toolchain as the plugin and executed with wine
inside a private prefix (WINEPREFIX, default ~/.cache/ts2fx-prefix).

Each shader file declares what to build with lines like
    // @shader <Symbol> <Entry> <Profile>
Symbols end up as  `kShader_<Symbol>[]`  (uint32_t DWORD stream, ready for CreatePixelShader/CreateVertexShader).
"""
import os
import re
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "build", "shaders")
SHADER_DIR = os.path.join(ROOT, "shaders")
OUT_HPP = os.path.join(ROOT, "include", "ts2", "postfx_shaders_gen.hpp")
WINEPREFIX = os.environ.get("WINEPREFIX", os.path.expanduser("~/.cache/ts2fx-prefix"))

KERNEL32_DEF = """LIBRARY KERNEL32.dll
EXPORTS
    LoadLibraryA@4
    GetProcAddress@8
    CreateFileA@28
    ReadFile@20
    WriteFile@20
    CloseHandle@4
    GetFileSize@8
    VirtualAlloc@16
    GetCommandLineA@0
    GetStdHandle@4
    ExitProcess@4
"""


def run(cmd, **kw):
    print("+", " ".join(cmd))
    return subprocess.run(cmd, **kw)


def build_compiler():
    os.makedirs(BUILD, exist_ok=True)
    exe = os.path.join(BUILD, "hlslc.exe")
    src = os.path.join(ROOT, "tools", "shadercomp", "hlslc.cpp")
    if os.path.exists(exe) and os.path.getmtime(exe) > os.path.getmtime(src):
        return exe
    defp = os.path.join(BUILD, "kernel32.def")
    lib = os.path.join(BUILD, "kernel32.lib")
    open(defp, "w").write(KERNEL32_DEF)
    subprocess.check_call(["llvm-dlltool", "-m", "i386", "-k", "-d", defp, "-l", lib])
    obj = os.path.join(BUILD, "hlslc.obj")
    subprocess.check_call(["clang++", "--target=i686-pc-windows-msvc", "-ffreestanding", "-std=c++20", "-O1",
                           "-fno-exceptions", "-fno-rtti", "-mno-sse2", "-c", src, "-o", obj])
    subprocess.check_call(["lld-link", "/MACHINE:X86", "/NODEFAULTLIB", "/SUBSYSTEM:CONSOLE",
                           "/ENTRY:mainCRTStartup", f"/OUT:{exe}", obj, lib])
    return exe


def wine_env():
    env = dict(os.environ)
    env["WINEPREFIX"] = WINEPREFIX
    env["WINEDEBUG"] = "-all"
    env["WINEDLLOVERRIDES"] = "winemenubuilder.exe=d"
    env.pop("DISPLAY", None) if not env.get("DISPLAY") else None
    return env


def winpath(p, env):
    out = subprocess.run(["winepath", "-w", p], env=env, capture_output=True, text=True, errors="replace")
    return out.stdout.strip() or ("Z:" + p.replace("/", "\\"))


def expand_includes(path, seen=()):
    """Textual #include "file" expansion (D3DCompile is called without an include handler)."""
    out = []
    for line in open(path, encoding="utf-8"):
        m = re.match(r'\s*#include\s+"([^"]+)"', line)
        if m:
            inc = os.path.join(os.path.dirname(path), m.group(1))
            out.append(expand_includes(inc, seen + (path,)))
        else:
            out.append(line)
    return "".join(out)


def parse_manifest():
    items = []
    for fn in sorted(os.listdir(SHADER_DIR)):
        if not fn.endswith(".hlsl"):
            continue
        path = os.path.join(SHADER_DIR, fn)
        for line in open(path, encoding="utf-8"):
            m = re.match(r"\s*//\s*@shader\s+(\w+)\s+(\w+)\s+(\w+)", line)
            if m:
                items.append((path, m.group(1), m.group(2), m.group(3)))
    return items


def main():
    exe = build_compiler()
    env = wine_env()
    items = parse_manifest()
    if not items:
        sys.exit("no shaders found")
    wexe = winpath(exe, env)
    out = ["// GENERATED by tools/build_shaders.py - do not edit.", "#pragma once", "#include <stdint.h>", ""]
    failed = False
    for path, sym, entry, prof in items:
        binp = os.path.join(BUILD, f"{sym}.bin")
        if os.path.exists(binp):
            os.remove(binp)
        expanded = os.path.join(BUILD, f"{sym}.expanded.hlsl")
        open(expanded, "w", encoding="utf-8").write(expand_includes(path))
        r = run(["wine", wexe, winpath(expanded, env), winpath(binp, env), entry, prof], env=env,
                capture_output=True, text=True, errors="replace")
        sys.stdout.write(r.stdout)
        sys.stdout.write(r.stderr)
        if r.returncode != 0 or not os.path.exists(binp):
            print(f"[FAIL] {sym} ({os.path.basename(path)} {entry} {prof})")
            failed = True
            continue
        data = open(binp, "rb").read()
        data += b"\0" * (-len(data) % 4)
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        print(f"[ok] {sym}: {len(data)} bytes")
        out.append(f"static const uint32_t kShader_{sym}[{len(words)}] = {{")
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",")
        out.append("};")
        out.append("")
    if failed:
        sys.exit(1)
    open(OUT_HPP, "w").write("\n".join(out))
    print("wrote", OUT_HPP)


if __name__ == "__main__":
    main()
